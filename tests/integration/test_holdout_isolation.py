"""Frozen on-disk provenance must reject training contamination before publication."""

import json
import subprocess

import pytest

from evidenceguard.digests import canonical_json_bytes, digest_file, digest_json_artifact
from evidenceguard.errors import ArtifactIntegrityError
from evidenceguard.scope import fit_scopes

GOLDEN = {
    "initial": {
        "grd_discount_member_rate_regression_v2": (
            "sha256:0d920803612c06764a81e45d3d25a57460ba8c03373692ec384c7e35e12443ba"
        ),
        "grd_query_limit_zero_regression_v2": (
            "sha256:9b1b7426914bf0f6bd0e476a04a1a2e40da78ccbe32011b8d73e2f7d4839d402"
        ),
    },
    "refined": {
        "grd_discount_member_rate_regression_v2": (
            "sha256:ce351b08f3ba13405362fdb50e257dfc0cf7ccb9facf28338b0b0764d3196f10"
        ),
        "grd_query_limit_zero_regression_v2": (
            "sha256:7fd96fa93b2560363e58e2b55b0a3bcd6873b58391ef5c33204211778fcc2f74"
        ),
    },
}


@pytest.mark.parametrize("attack", ["append_holdout_to_train", "holdout_label", "resigned_split"])
def test_disk_contamination_cannot_reach_a_new_fit(mutable_replay_workspace, monkeypatch, attack):
    root = mutable_replay_workspace
    fitted = root / "artifacts/fitted"
    before = {p: digest_file(p) for p in fitted.rglob("*.json")}
    if attack == "resigned_split":
        path = root / "benchmarks/splits/scope_v1.json"
        payload = json.loads(path.read_bytes())
        group = payload["phases"]["grd_discount_member_rate_regression_v2"]
        held = group["holdout"].pop()
        group["initial"].append(held)
        payload["artifact_digest"] = digest_json_artifact(payload)
    else:
        held = json.loads((root / "benchmarks/holdout/discount_scope_samples.json").read_bytes())
        if attack == "append_holdout_to_train":
            path = root / "benchmarks/train/discount_scope_samples.json"
            payload = json.loads(path.read_bytes()) + [held[0]]
        else:
            path = root / "benchmarks/holdout/discount_scope_samples.json"
            payload = held
            payload[0]["labels"]["contract_compliant"] = not payload[0]["labels"][
                "contract_compliant"
            ]
    path.write_bytes(canonical_json_bytes(payload))

    def forbidden(*a, **k):
        pytest.fail("Contaminated training inputs must never execute a target")

    monkeypatch.setattr(subprocess, "Popen", forbidden)
    with pytest.raises(ArtifactIntegrityError):
        fit_scopes(
            "experiments/scope_v1.json", phase="refined", output="artifacts/refused-fit", cwd=root
        )
    assert not (root / "artifacts/refused-fit").exists()
    assert before == {p: digest_file(p) for p in fitted.rglob("*.json")}


@pytest.mark.parametrize("phase,total", [("initial", 7), ("refined", 9)])
def test_public_fit_reuses_exact_training_members_and_pre_d13_learning_golden(
    replay_workspace,
    monkeypatch,
    phase,
    total,
):
    # These four digests are the previously published D12 pure learning results, not outputs
    # generated by this test. They protect the frozen experiment from this audit's code changes.
    root = replay_workspace
    before = {
        p: (p.read_bytes(), p.stat().st_mtime_ns)
        for p in (root / "artifacts/fitted").rglob("*.json")
    }

    def forbidden(*a, **k):
        pytest.fail("Fitting verified static training inputs must not execute targets")

    monkeypatch.setattr(subprocess, "Popen", forbidden)
    fit = fit_scopes(
        "experiments/scope_v1.json", phase=phase, output=f"artifacts/fitted/{phase}", cwd=root
    )
    assert sum(len(g.training_sample_ids) for g in fit.groups) == total
    assert all(s.startswith("train-") for g in fit.groups for s in g.training_sample_ids)
    assert {g.guard_id: g.learning_digest for g in fit.groups} == GOLDEN[phase]
    assert before == {
        p: (p.read_bytes(), p.stat().st_mtime_ns)
        for p in (root / "artifacts/fitted").rglob("*.json")
    }
