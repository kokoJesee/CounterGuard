def render_minimal_test(contract, case_ids):
    ids = tuple(case_ids)
    _require(bool(ids) and ids == tuple(sorted(set(ids))), "guard_case_ids_not_canonical")
    cases = tuple(case for case in contract.cases if case.case_id in ids)
    _require(tuple(case.case_id for case in cases) == ids, "guard_case_ids_outside_contract")
    # Do not alter the capture generator or frozen historical templates.
    return render_standalone_test(contract.model_copy(update={"cases": cases})).replace(
        b"Generated by standalone-test.v1;", b"Generated by standalone-guard-test.v1;", 1
    )


def compilation_sources(repo, workspace, compilation_ref):
    plan = _model(workspace, compilation_ref, StandaloneCompilation)
    _require(
        compilation_ref == plan.output_ref + "/compilation.json"
        and plan.implementation_digests == inspection_implementation_digests()
        and bool(plan.review_reason.strip()),
        "guard_compilation_stale_or_unreviewed",
    )
    evidence, (capture, binding, contract) = _load_verified_evidence(
        repo, workspace, plan.source_evidence_ref
    )
    _require(
        evidence.reproduced
        and bool(evidence.failing_case_ids)
        and evidence.artifact_digest == plan.source_evidence_digest,
        "guard_requires_reproduced_current_evidence",
    )
    return plan, evidence, capture, binding, contract


def snapshot_scope(plan, evidence, binding, contract):
    return _seal(
        StandaloneScope(
            guard_id=plan.guard_id,
            source_evidence_digest=evidence.artifact_digest,
            binding_digest=binding["artifact_digest"],
            target_module=contract.target_module,
            target_symbol=contract.target_symbol,
            import_root=contract.import_root,
            contract_ref=binding["contract_ref"],
            contract_digest=evidence.contract_digest,
            snapshots={
                role: {
                    pin["path"]: pin["content_digest"]
                    for pin in binding["runtime_assessments"][role]["files"]
                }
                for role in ("buggy", "fixed")
            },
            artifact_digest=ZERO,
        )
    )


def authorize_guard_inputs(
    request,
    *,
    workspace,
    runtime,
    contract,
    binding,
    revision,
    source_pins,
    source_refs,
    case_ids,
    evidence,
    capture,
    purpose,
    provenance_digest,
    scope_digest=None,
    registry_entry_digest=None,
    registry_event_tip_digest=None,
    inspection_digest=None,
):
    """Closed shared data gate; callers independently establish self-check/replay authority."""
    _require(request.run_id is not None, "guard_run_identity_required")
    _require(
        request.cwd == runtime and request.artifact_root == runtime / "r", "guard_runtime_mismatch"
    )
    _require(
        request.target
        == TargetRef(
            module=contract.target_module,
            symbol=contract.target_symbol,
            source_ref=contract.source_ref,
        )
        and request.target_digest == source_pins[contract.source_ref]["content_digest"]
        and request.contract_id == contract.contract_id
        and request.contract_digest == evidence.contract_digest
        and request.test_path == runtime / TEST_REF
        and request.contract_path == runtime / CONTRACT_REF
        and request.timeout_seconds == capture.timeout_seconds
        and request.known_case_ids == tuple(runtime_case_id(case_id) for case_id in case_ids),
        "guard_request_exceeds_reviewed_inputs",
    )
    expected_test = render_minimal_test(contract, case_ids)
    _require(_file(runtime, TEST_REF) == expected_test, "guard_test_not_minimal_canonical")
    head_pins = {pin["path"]: pin for pin in binding["trees"]["head"]["files"]}
    origins = {ref: ref for ref in source_refs} | {CONTRACT_REF: binding["contract_ref"]}
    pins = []
    for ref, origin in sorted(origins.items()):
        pin = head_pins[origin] if ref == CONTRACT_REF else source_pins[origin]
        _require(digest_bytes(_file(runtime, ref)) == pin["content_digest"], "guard_input_mismatch")
        pins.append(
            ExecutionInputPin(
                path=ref, object_id=pin["object_id"], content_digest=pin["content_digest"]
            )
        )
    return _seal(
        StandaloneGuardAuthorization(
            purpose=purpose,
            role=request.role,
            provenance_digest=provenance_digest,
            evidence_digest=evidence.artifact_digest,
            binding_digest=binding["artifact_digest"],
            target_revision=revision,
            assertion_head=binding["head_commit"],
            image_digest=capture.runner.image_digest,
            runner_review_digest=capture.runner.artifact_digest,
            policy_digest=capture.policy_digest,
            implementation_digests=inspection_implementation_digests(),
            request_digest=_request_digest(request),
            input_pins=tuple(pins),
            input_origins=origins,
            import_root=contract.import_root,
            test_ref=TEST_REF,
            test_digest=digest_bytes(expected_test),
            known_case_ids=request.known_case_ids,
            case_id_map={case_id: runtime_case_id(case_id) for case_id in case_ids},
            scope_digest=scope_digest,
            registry_entry_digest=registry_entry_digest,
            registry_event_tip_digest=registry_event_tip_digest,
            inspection_digest=inspection_digest,
            artifact_digest=ZERO,
        )
    )


def authorize_self_check(repo, workspace, compilation_ref, request, *, sources=None):
    plan, evidence, capture, binding, contract = sources or compilation_sources(
        repo, workspace, compilation_ref
    )
    _require(request.role in {RunRole.BUGGY, RunRole.FIXED}, "guard_self_check_role_mismatch")
    role = request.role.value
    runtime = workspace / plan.output_ref / ("b" if request.role is RunRole.BUGGY else "f")
    return authorize_guard_inputs(
        request,
        workspace=workspace,
        runtime=runtime,
        contract=contract,
        binding=binding,
        revision=binding["trees"][role]["commit"],
        source_pins={pin["path"]: pin for pin in binding["trees"][role]["files"]},
        source_refs=[pin["path"] for pin in binding["runtime_assessments"][role]["files"]],
        case_ids=evidence.failing_case_ids,
        evidence=evidence,
        capture=capture,
        purpose="minimal_guard_self_check",
        provenance_digest=plan.artifact_digest,
    )


@dataclass(frozen=True)
class GuardDockerExecutor:
    authorization: StandaloneGuardAuthorization
    authorizer: object
    capture: object
    policy: DockerPolicyV1 = DockerPolicyV1()

    def verify(self, request):
        _require(self.policy == DockerPolicyV1(), "guard_executor_policy_mismatch")
        _require(self.authorizer(request) == self.authorization, "guard_authorization_stale")

    def execute(self, request):
        self.verify(request)
        executable = _docker_executable()
        _require_image_identity(executable, self.authorization.image_digest, self.policy)
        run = _execute_with_adapter(request, _AdmittedDockerProcess(self, executable))
        write_immutable(request.artifact_root / "record.json", canonical_json_bytes(run))
        try:
            self.verify(request)
            _verify_run_envelope(run, request, self.capture)
            verify_run_record(
                run, cwd=request.cwd, known_case_ids=self.authorization.known_case_ids
            )
        except (ArtifactIntegrityError, RepositoryProblem, OSError, ValueError) as error:
            raise GuardReplayIntegrityError("guard_inputs_changed_after_execution", run) from error
        return run


def guard_request(runtime, contract, evidence, capture, source_pin, role, run_id):
    return PytestRunRequest(
        role=role,
        contract_id=contract.contract_id,
        contract_digest=evidence.contract_digest,
        target=TargetRef(
            module=contract.target_module,
            symbol=contract.target_symbol,
            source_ref=contract.source_ref,
        ),
        target_digest=source_pin["content_digest"],
        test_path=runtime / TEST_REF,
        contract_path=runtime / CONTRACT_REF,
        known_case_ids=tuple(runtime_case_id(case_id) for case_id in evidence.failing_case_ids),
        cwd=runtime,
        artifact_root=runtime / "r",
        run_id=run_id,
        timeout_seconds=capture.timeout_seconds,
    )


def verify_guard_run(item, request, authorization, capture, workspace):
    stored = RunRecord.model_validate_json(_file(workspace, item.record_ref))
    _require(
        stored == item.run
        and stored.role is request.role
        and stored.target == request.target
        and stored.target_digest == request.target_digest
        and stored.contract_id == request.contract_id
        and stored.contract_digest == request.contract_digest
        and stored.cwd == "."
        and stored.timeout_seconds == request.timeout_seconds,
        "guard_run_identity_mismatch",
    )
    _verify_run_envelope(stored, request, capture)
    for ref in (stored.stdout_ref, stored.stderr_ref, stored.junit_ref):
        _file(request.cwd, ref)
    verify_run_record(stored, cwd=request.cwd, known_case_ids=authorization.known_case_ids)


def _verify_value(repo, workspace, path_ref, guard, *, sources=None):
    sources = sources or compilation_sources(repo, workspace, guard.compilation_ref)
    plan, evidence, capture, binding, contract = sources
    _require(
        path_ref == plan.output_ref + "/guard.json"
        and guard.guard_id == plan.guard_id
        and guard.compilation_digest == plan.artifact_digest
        and guard.source_evidence_ref == plan.source_evidence_ref
        and guard.source_evidence_digest == evidence.artifact_digest
        and guard.contract_id == evidence.contract_id
        and guard.contract_digest == evidence.contract_digest
        and guard.case_ids == evidence.failing_case_ids
        and guard.test_ref == plan.output_ref + "/test_guard.py"
        and guard.scope_ref == plan.output_ref + "/scope.json",
        "guard_provenance_or_minimality_mismatch",
    )
    expected_test = render_minimal_test(contract, evidence.failing_case_ids)
    _require(
        _file(workspace, guard.test_ref) == expected_test
        and guard.test_digest == digest_bytes(expected_test),
        "guard_test_mismatch",
    )
    scope = _model(workspace, guard.scope_ref, StandaloneScope)
    _require(
        scope == snapshot_scope(plan, evidence, binding, contract)
        and guard.scope_digest == scope.artifact_digest,
        "guard_scope_mismatch",
    )
    for item, role, suffix in (
        (guard.buggy_check, RunRole.BUGGY, "b"),
        (guard.fixed_check, RunRole.FIXED, "f"),
    ):
        runtime_ref = plan.output_ref + "/" + suffix
        _require(
            item.workspace_ref == runtime_ref
            and item.record_ref == runtime_ref + "/r/record.json"
            and item.authorization_ref == runtime_ref + "/authorization.json",
            "guard_check_layout_mismatch",
        )
        source_pin = next(
            pin
            for pin in binding["trees"][role.value]["files"]
            if pin["path"] == contract.source_ref
        )
        request = guard_request(
            workspace / runtime_ref, contract, evidence, capture, source_pin, role, item.run.run_id
        )
        auth = _model(workspace, item.authorization_ref, StandaloneGuardAuthorization)
        _require(
            auth
            == authorize_self_check(
                repo, workspace, guard.compilation_ref, request, sources=sources
            ),
            "guard_check_authorization_mismatch",
        )
        verify_guard_run(item, request, auth, capture, workspace)
        expected = RunOutcome.TEST_FAILED if role is RunRole.BUGGY else RunOutcome.PASSED
        _require(item.run.outcome is expected, "guard_self_check_not_reproduced")
        _require(
            tuple(case.case_id for case in item.run.case_results) == auth.known_case_ids,
            "guard_self_check_case_set_mismatch",
        )
        if role is RunRole.BUGGY:
            _require(
                all(case.outcome is CaseOutcome.FAILED for case in item.run.case_results),
                "guard_contains_case_that_did_not_fail",
            )
    return guard


def verify_standalone_guard(repo: Path, path: Path, *, cwd=None):
    return verify_standalone_guard_chain(repo, path, cwd=cwd)[0]


def verify_standalone_guard_chain(repo: Path, path: Path, *, cwd=None):
    workspace = (cwd or Path.cwd()).resolve(strict=True)
    ref = _ref(path, workspace)
    guard = _model(workspace, ref, StandaloneGuard)
    sources = compilation_sources(repo, workspace, guard.compilation_ref)
    return _verify_value(repo, workspace, ref, guard, sources=sources), sources


def compile_standalone_guard(
    repo: Path, evidence_path: Path, *, guard_id, review_reason, output: Path, cwd=None
):
    workspace = (cwd or Path.cwd()).resolve(strict=True)
    TypeAdapter(GuardId).validate_python(guard_id)
    TypeAdapter(ReviewReason).validate_python(review_reason)
    if not review_reason.strip():
        raise ValueError("Guard semantic/snapshot review reason must not be blank")
    # Invalid/nonreproduced evidence cannot create a Candidate.
    evidence_ref = _ref(evidence_path, workspace)
    evidence = verify_standalone_evidence(repo, evidence_path, cwd=workspace)
    if not evidence.reproduced or not evidence.failing_case_ids:
        raise InvalidEvidenceError("guard_requires_reproduced_current_evidence")
    output = _new_output(repo, output, workspace)
    plan = _seal(
        StandaloneCompilation(
            guard_id=guard_id,
            created_at=datetime.now(UTC),
            output_ref=output.relative_to(workspace).as_posix(),
            source_evidence_ref=evidence_ref,
            source_evidence_digest=evidence.artifact_digest,
            review_reason=review_reason,
            implementation_digests=inspection_implementation_digests(),
            artifact_digest=ZERO,
        )
    )
    plan_ref = plan.output_ref + "/compilation.json"
    write_immutable(workspace / plan_ref, canonical_json_bytes(plan))
    completed = []
    try:
        _, _, capture, binding, contract = compilation_sources(repo, workspace, plan_ref)
        test = render_minimal_test(contract, evidence.failing_case_ids)
        write_immutable(output / "test_guard.py", test)
        scope = snapshot_scope(plan, evidence, binding, contract)
        write_immutable(output / "scope.json", canonical_json_bytes(scope))
        checks = []
        for role, suffix in ((RunRole.BUGGY, "b"), (RunRole.FIXED, "f")):
            runtime = output / suffix
            original = evidence.buggy if role is RunRole.BUGGY else evidence.fixed
            for pin in binding["runtime_assessments"][role.value]["files"]:
                write_immutable(
                    runtime / pin["path"], _file(workspace / original.workspace_ref, pin["path"])
                )
            write_immutable(
                runtime / CONTRACT_REF, _file(workspace / original.workspace_ref, CONTRACT_REF)
            )
            write_immutable(runtime / TEST_REF, test)
            pin = next(
                pin
                for pin in binding["trees"][role.value]["files"]
                if pin["path"] == contract.source_ref
            )
            request = guard_request(
                runtime, contract, evidence, capture, pin, role, "run_" + uuid4().hex
            )

            def authorize(run_request):
                return authorize_self_check(repo, workspace, plan_ref, run_request)

            auth = authorize(request)
            auth_ref = runtime.relative_to(workspace).as_posix() + "/authorization.json"
            write_immutable(workspace / auth_ref, canonical_json_bytes(auth))
            run = GuardDockerExecutor(auth, authorize, capture).execute(request)
            item = StandaloneExecution(
                workspace_ref=runtime.relative_to(workspace).as_posix(),
                authorization_ref=auth_ref,
                record_ref=(runtime / "r/record.json").relative_to(workspace).as_posix(),
                run=run,
            )
            completed.append(item.record_ref)
            expected = RunOutcome.TEST_FAILED if role is RunRole.BUGGY else RunOutcome.PASSED
            if run.outcome is not expected or (
                role is RunRole.BUGGY
                and not all(case.outcome is CaseOutcome.FAILED for case in run.case_results)
            ):
                raise GuardSelfCheckError(run)
            checks.append(item)
        guard = _seal(
            StandaloneGuard(
                guard_id=guard_id,
                created_at=datetime.now(UTC),
                compilation_ref=plan_ref,
                compilation_digest=plan.artifact_digest,
                source_evidence_ref=evidence_ref,
                source_evidence_digest=evidence.artifact_digest,
                contract_id=evidence.contract_id,
                contract_digest=evidence.contract_digest,
                case_ids=evidence.failing_case_ids,
                test_ref=plan.output_ref + "/test_guard.py",
                test_digest=digest_bytes(test),
                scope_ref=plan.output_ref + "/scope.json",
                scope_digest=scope.artifact_digest,
                buggy_check=checks[0],
                fixed_check=checks[1],
                artifact_digest=ZERO,
            )
        )
        _verify_value(repo, workspace, plan.output_ref + "/guard.json", guard)
        raw = canonical_json_bytes(guard)
        _require(len(raw) <= 4 * 1024 * 1024, "guard_publication_byte_budget_exceeded")
        write_immutable(output / "guard.json", raw)
        return guard
    except (
        ArtifactIntegrityError,
        GuardSelfCheckError,
        RepositoryProblem,
        OSError,
        ValueError,
    ) as error:
        if isinstance(error, GuardReplayIntegrityError):
            completed.append(
                (output / ("b" if error.run.role is RunRole.BUGGY else "f") / "r/record.json")
                .relative_to(workspace)
                .as_posix()
            )
        failure = {
            "schema_version": "standalone-compilation-failure.v1",
            "created_at": datetime.now(UTC).isoformat(),
            "guard_id": guard_id,
            "published": False,
            "reason_type": type(error).__name__,
            "completed_record_refs": completed,
        }
        failure["artifact_digest"] = digest_json_artifact(failure)
        write_immutable(output / "compilation-failure.json", canonical_json_bytes(failure))
        raise
