"""Trusted literal-only research renderers; source oracle and target witness stay separate."""

from counterguard.digests import canonical_json_bytes
from counterguard.standalone_test import render_standalone_test


def render_study_test(contract, target, mapped_cases, witness=None):
    value = contract.model_copy(
        update={
            "target_module": target.module,
            "target_symbol": target.symbol,
            "cases": mapped_cases,
        }
    )
    rendered = render_standalone_test(value)
    if witness is None:
        return rendered.replace(
            b"Generated by standalone-test.v1;", b"Generated by study-mapped-test.v1;", 1
        ).replace(b"Generated by standalone-test.v2;", b"Generated by study-mapped-test.v1;", 1)
    expected = {c.case_id: c.stdout for c in witness.cases}
    rows = [
        {**c.model_dump(mode="json"), "stdout": expected[c.case_id]}
        for c in mapped_cases
        if c.case_id in expected
    ]
    payload = canonical_json_bytes(rows).decode()
    # Reuse the closed literal decoder and collection-time target import, not its oracle.
    header = rendered.decode().split("@pytest.mark.parametrize", 1)[0]
    original = canonical_json_bytes(mapped_cases).decode()
    header = header.replace(
        f"CASES = json.loads({original!r})", f"CASES = json.loads({payload!r})", 1
    )
    header = header.replace(
        "Generated by standalone-test.v1;", "Generated by study-stdout-test.v1;", 1
    ).replace("Generated by standalone-test.v2;", "Generated by study-stdout-test.v1;", 1)
    return (
        header + "\nimport contextlib\nimport io\n\n"
        "class BoundedObserver(io.StringIO):\n"
        "    def write(self, text):\n"
        "        try:\n"
        "            if self.tell() + len(text) > 8192:\n"
        "                pytest.exit('study_stdout_observer_limit', returncode=3)\n"
        "            return super().write(text)\n"
        "        except Exception: pytest.exit('study_stdout_observer_failed', returncode=3)\n\n"
        "@pytest.fixture\n"
        "def observer():\n"
        "    stream = BoundedObserver()\n"
        "    try: yield stream\n"
        "    finally: stream.close()\n\n"
        "@contextlib.contextmanager\n"
        "def observe(stream):\n"
        "    try:\n"
        "        manager = contextlib.redirect_stdout(stream)\n"
        "        manager.__enter__()\n"
        "    except Exception: pytest.exit('study_stdout_observer_failed', returncode=3)\n"
        "    try: yield\n"
        "    finally:\n"
        "        try: manager.__exit__(None, None, None)\n"
        "        except Exception: pytest.exit('study_stdout_observer_failed', returncode=3)\n\n"
        "@pytest.mark.parametrize('case', "
        "[pytest.param(c, id='case-' + c['case_id'][5:]) for c in CASES])\n"
        "def test_guard_case(case, observer):\n"
        "    args = [literal(x) for x in case['positional_args']]\n"
        "    kwargs = {x['name']: literal(x['literal']) for x in case['keyword_args']}\n"
        "    with observe(observer): TARGET(*args, **kwargs)\n"
        "    try: actual = observer.getvalue()\n"
        "    except Exception: pytest.exit('study_stdout_observer_failed', returncode=3)\n"
        "    assert actual == case['stdout']\n"
    ).encode()
