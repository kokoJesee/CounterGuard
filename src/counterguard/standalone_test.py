"""Canonical tests from typed literal data; never evaluate a target on the host."""

from counterguard.contract_draft_models import DraftMatchCase
from counterguard.digests import canonical_json_bytes
from counterguard.standalone_contracts import StandaloneContract, StandaloneContractV4

GENERATOR = "standalone-test.v1"
CONTROL = "cg_control"
TEST_REF = CONTROL + "/test_capture.py"
CONTRACT_REF = CONTROL + "/contract.json"


def runtime_case_id(case_id: str) -> str:
    # contract-proposal.v1 IDs are immutable. The existing JUnit mapper accepts
    # hyphens; use an injective transport spelling instead of changing its rules.
    return "case-" + case_id.removeprefix("case_")


def render_standalone_test(contract: StandaloneContract) -> bytes:
    if not isinstance(contract, StandaloneContractV4) and any(
        isinstance(case, DraftMatchCase) for case in contract.cases
    ):
        raise ValueError("Message cases require contract.v4")
    return _render_literal_test(contract, message_cases=isinstance(contract, StandaloneContractV4))


def _render_literal_test(contract, *, message_cases, generator=GENERATOR):
    """Byte template shared by independently validated, versioned contract callers."""
    payload = canonical_json_bytes(contract.cases).decode()
    rendered = (
        f'"""Generated by {generator}; committed test projection, literal data only."""\n'
        "import importlib\nimport json\nimport os\nimport pytest\n\n"
        f"CASES = json.loads({payload!r})\n"
        f"MODULE = {contract.target_module!r}\nSYMBOL = {contract.target_symbol!r}\n"
        "if os.environ.get('COUNTERGUARD_TARGET') != MODULE or "
        "os.environ.get('COUNTERGUARD_SYMBOL') != SYMBOL:\n"
        "    raise pytest.UsageError('This test requires its admitted Docker target')\n"
        # Collection-time import ensures any import-time exception is an
        # infrastructure/collection failure, outside all raises oracles.
        "TARGET = getattr(importlib.import_module(MODULE), SYMBOL)\n"
        "ERRORS = {'ValueError': ValueError, 'TypeError': TypeError, "
        "'OverflowError': OverflowError}\n"
        "\n"
        "def literal(item):\n"
        "    kind = item['kind']\n"
        "    if kind == 'bytes': return bytes.fromhex(item['value'])\n"
        "    if kind == 'list': return [literal(x) for x in item['items']]\n"
        "    if kind == 'tuple': return tuple(literal(x) for x in item['items'])\n"
        "    if kind == 'dict': return {literal(k): literal(v) for k, v in item['entries']}\n"
        "    return item['value']\n\n"
        "@pytest.mark.parametrize('case', "
        "[pytest.param(c, id='case-' + c['case_id'][5:]) for c in CASES])\n"
        "def test_guard_case(case):\n"
        "    args = [literal(x) for x in case['positional_args']]\n"
        "    kwargs = {x['name']: literal(x['literal']) for x in case['keyword_args']}\n"
        "    oracle = case['oracle']\n"
        "    if oracle == 'raises':\n"
        "        with pytest.raises(ERRORS[case['exception']]): TARGET(*args, **kwargs)\n"
        "        return\n"
        "    result = TARGET(*args, **kwargs)\n"
        "    if oracle == 'truthy': assert result\n"
        "    elif oracle == 'falsey': assert not result\n"
        "    else:\n"
        "        expected = literal(case['expected'])\n"
        "        if oracle == 'eq': assert result == expected\n"
        "        elif oracle == 'ne': assert result != expected\n"
        "        elif oracle == 'is': assert result is expected\n"
        "        elif oracle == 'is_not': assert result is not expected\n"
        "        else: raise pytest.UsageError('Unsupported admitted oracle')\n"
    ).encode()
    if message_cases:
        rendered = rendered.replace(
            b"Generated by standalone-test.v1;", b"Generated by standalone-test.v2;", 1
        )
        rendered = rendered.replace(
            b"with pytest.raises(ERRORS[case['exception']]): TARGET(*args, **kwargs)",
            b"with pytest.raises(ERRORS[case['exception']], "
            b"**({'match': case['exception_match']} if 'exception_match' in case else {})): "
            b"TARGET(*args, **kwargs)",
            1,
        )
    return rendered
