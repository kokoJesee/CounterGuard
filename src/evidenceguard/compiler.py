_GUARD_ID = re.compile(r"^grd_[A-Za-z0-9][A-Za-z0-9_-]*$")
_EMPTY_DIGEST = "sha256:" + "0" * 64

_TEST_TEMPLATE = '''"""Minimal regression assertions generated by EvidenceGuard guard-test.v1."""

import importlib
import json
import os
from decimal import Decimal

import pytest

DATA = json.loads(__PAYLOAD__)
EXCEPTIONS = {"ValueError": ValueError, "TypeError": TypeError, "OverflowError": OverflowError}


def convert(value, kind):
    return Decimal(value) if kind == "decimal" else value


@pytest.fixture
def target():
    result = importlib.import_module(os.environ["EVIDENCEGUARD_TARGET"])
    for part in os.environ["EVIDENCEGUARD_SYMBOL"].split("."):
        result = getattr(result, part)
    return result


@pytest.mark.parametrize("case", [pytest.param(case, id=case["case_id"]) for case in DATA["cases"]])
def test_guard_case(target, case):
    kwargs = {
        name: convert(value, DATA["argument_types"][name])
        for name, value in case["args"].items()
    }
    if "raises" in case:
        with pytest.raises(EXCEPTIONS[case["raises"]]):
            target(**kwargs)
    else:
        assert target(**kwargs) == convert(case["expected"], DATA["return_type"])
'''

_TEST_TEMPLATE_V2 = _TEST_TEMPLATE.replace("guard-test.v1", "guard-test.v2").replace(
    '    result = importlib.import_module(os.environ["EVIDENCEGUARD_TARGET"])\n'
    '    for part in os.environ["EVIDENCEGUARD_SYMBOL"].split("."):',
    '    module = os.environ.get("EVIDENCEGUARD_TARGET")\n'
    '    symbol = os.environ.get("EVIDENCEGUARD_SYMBOL")\n'
    "    if not module or not symbol:\n"
    "        raise pytest.UsageError(\n"
    '            "Missing Guard target. Use evidenceguard guard run <guard.json> "\n'
    '            "--target module:symbol, or set EVIDENCEGUARD_TARGET and "\n'
    '            "EVIDENCEGUARD_SYMBOL before running pytest."\n'
    "        )\n"
    "    result = importlib.import_module(module)\n"
    '    for part in symbol.split("."):',
)


@dataclass(frozen=True, slots=True)
class CompileRequest:
    guard_id: str
    evidence_path: Path
    cwd: Path
    artifact_root: Path


def compile_guard(request: CompileRequest) -> Guard:
    """Audit the source, compile only failed cases, and self-check before publishing."""
    if not _GUARD_ID.fullmatch(request.guard_id):
        raise ValueError("guard_id must start with 'grd_' and contain safe characters")
    workspace = request.cwd.resolve(strict=True)
    evidence_path = _workspace_path(request.evidence_path, workspace)
    evidence = verify_evidence(evidence_path, cwd=workspace)
    if not evidence.reproduced or not evidence.failing_case_ids:
        raise InvalidEvidenceError(
            "Compiler requires reproduced Evidence with a nonempty failure set"
        )
    if request.guard_id == evidence.contract_id:
        raise ValueError("Guard and contract must have independent identities")
    version_suffix = re.search(r"_v([1-9]\d*)$", request.guard_id)
    guard_version = int(version_suffix.group(1)) if version_suffix else 1
    contract = json.loads((workspace / evidence.contract_ref).read_bytes())
    cases = _minimal_cases(contract, evidence)
    interface = TargetInterface.model_validate(
        {key: contract[key] for key in TargetInterface.model_fields}
    )
    payload = {
        "argument_types": contract["argument_types"],
        "return_type": contract["return_type"],
        "cases": [case.model_dump(mode="json") for case in cases],
    }
    test_bytes = _render_test(payload)
    artifact_root = _workspace_path(request.artifact_root, workspace)
    guard_dir = artifact_root / "guards" / request.guard_id
    guard_path = guard_dir / "guard.json"
    test_path = guard_dir / "test_guard.py"
    if guard_path.exists():
        guard = verify_guard(guard_path, cwd=workspace)
        if guard.source_evidence_digest != evidence.artifact_digest:
            raise ArtifactIntegrityError("Guard ID already exists with different source Evidence")
        if guard.generator_version != "guard-test.v2" or guard.guard_version != guard_version:
            raise ArtifactIntegrityError(
                "Guard ID already exists with a different generator/version"
            )
        if guard.source_evidence_ref != evidence_path.relative_to(workspace).as_posix():
            raise ArtifactIntegrityError(
                "Guard ID already exists with a different source reference"
            )
        return guard

    # The JSON file is the completion marker. A failed self-check leaves the
    # generated candidate test and raw run logs, but no consumable Guard JSON.
    write_immutable(test_path, test_bytes)
    run = run_pytest(
        PytestRunRequest(
            role=RunRole.REPLAY,
            contract_id=evidence.contract_id,
            contract_digest=evidence.contract_digest,
            target=evidence.fixed_target,
            target_digest=evidence.fixed_target_digest,
            test_path=test_path,
            known_case_ids=tuple(case.case_id for case in cases),
            cwd=workspace,
            artifact_root=artifact_root,
        )
    )
    if run.outcome is not RunOutcome.PASSED:
        raise GuardSelfCheckError(run)
    # Re-audit after executing the generated code to prevent publishing stale inputs.
    verify_evidence(evidence_path, cwd=workspace)
    draft = Guard(
        guard_id=request.guard_id,
        guard_version=guard_version,
        created_at=datetime.now(UTC),
        source_evidence_id=evidence.evidence_id,
        source_evidence_ref=evidence_path.relative_to(workspace).as_posix(),
        source_evidence_digest=evidence.artifact_digest,
        contract_id=evidence.contract_id,
        contract_digest=evidence.contract_digest,
        target_interface=interface,
        argument_types=contract["argument_types"],
        return_type=contract["return_type"],
        cases=cases,
        test_ref=test_path.relative_to(workspace).as_posix(),
        test_digest=digest_bytes(test_bytes),
        source_buggy_digest=evidence.buggy_target_digest,
        source_fixed_digest=evidence.fixed_target_digest,
        validation_run=run,
        artifact_digest=_EMPTY_DIGEST,
    )
    if digest_file(test_path) != draft.test_digest:
        raise ArtifactIntegrityError("Generated test changed during self-check")
    guard = Guard.model_validate(
        {**draft.model_dump(), "artifact_digest": digest_json_artifact(draft)}
    )
    write_immutable(guard_path, canonical_json_bytes(guard))
    return guard


def load_guard(path: str | Path, *, cwd: str | Path) -> Guard:
    """Load a Guard without requiring its historical contract or Evidence files."""
    workspace = Path(cwd).resolve(strict=True)
    guard_path = _workspace_path(Path(path), workspace)
    try:
        guard = Guard.model_validate_json(guard_path.read_bytes())
    except (OSError, ValidationError) as error:
        raise ArtifactIntegrityError(f"Cannot load valid Guard: {guard_path}") from error
    if digest_json_artifact(guard) != guard.artifact_digest:
        raise ArtifactIntegrityError("Guard artifact digest mismatch")
    if guard_path.name != "guard.json" or guard_path.parent.name != guard.guard_id:
        raise ArtifactIntegrityError("Guard directory and identity do not match")
    if guard_path.parent.parent.name != "guards":
        raise ArtifactIntegrityError("Guard parent directory must be named 'guards'")
    test_path = _workspace_path(workspace / guard.test_ref, workspace)
    if test_path != guard_path.parent / "test_guard.py":
        raise ArtifactIntegrityError("Guard test reference must point to its own test_guard.py")
    payload = {
        "argument_types": guard.argument_types,
        "return_type": guard.return_type,
        "cases": [case.model_dump(mode="json") for case in guard.cases],
    }
    try:
        test_bytes = test_path.read_bytes()
    except OSError as error:
        raise ArtifactIntegrityError("Guard test is missing") from error
    if digest_bytes(test_bytes) != guard.test_digest or test_bytes != _render_test(
        payload, guard.generator_version
    ):
        raise ArtifactIntegrityError("Guard test digest or generated content mismatch")
    return guard


def verify_guard(path: str | Path, *, cwd: str | Path) -> Guard:
    """Audit the Guard, its source chain, embedded assertions, and self-check logs."""
    workspace = Path(cwd).resolve(strict=True)
    guard = load_guard(path, cwd=workspace)
    evidence = verify_evidence(workspace / guard.source_evidence_ref, cwd=workspace)
    if not evidence.reproduced:
        raise ArtifactIntegrityError("Guard source Evidence was not reproduced")
    expected = (
        evidence.evidence_id,
        evidence.artifact_digest,
        evidence.contract_id,
        evidence.contract_digest,
        evidence.buggy_target_digest,
        evidence.fixed_target_digest,
    )
    actual = (
        guard.source_evidence_id,
        guard.source_evidence_digest,
        guard.contract_id,
        guard.contract_digest,
        guard.source_buggy_digest,
        guard.source_fixed_digest,
    )
    if actual != expected or guard.validation_run.target != evidence.fixed_target:
        raise ArtifactIntegrityError("Guard and Evidence provenance mismatch")
    contract = json.loads((workspace / evidence.contract_ref).read_bytes())
    expected_cases = _minimal_cases(contract, evidence)
    if guard.cases != expected_cases:
        raise ArtifactIntegrityError(
            "Guard case set or oracle does not match minimal Evidence failures"
        )
    expected_interface = {key: contract[key] for key in TargetInterface.model_fields}
    if (
        guard.target_interface.model_dump() != expected_interface
        or guard.argument_types != contract["argument_types"]
        or guard.return_type != contract["return_type"]
    ):
        raise ArtifactIntegrityError("Guard contract interface mismatch")
    run = guard.validation_run
    for ref, expected_digest in (
        (run.stdout_ref, run.stdout_digest),
        (run.stderr_ref, run.stderr_digest),
        (run.junit_ref, run.junit_digest),
    ):
        try:
            actual_digest = digest_file(_workspace_path(workspace / ref, workspace))
        except OSError as error:
            raise ArtifactIntegrityError("Guard self-check log is missing") from error
        if actual_digest != expected_digest:
            raise ArtifactIntegrityError("Guard self-check log digest mismatch")
    return guard


def run_guard(
    path: str | Path,
    target: str,
    *,
    cwd: str | Path,
    artifact_root: str | Path = "artifacts",
    timeout_seconds: float = 30.0,
) -> RunRecord:
    """Direct trusted smoke replay; Scope decisions are introduced in Day 8."""
    workspace = Path(cwd).resolve(strict=True)
    guard = load_guard(path, cwd=workspace)
    target_ref, target_digest = parse_target_ref(target, cwd=workspace)
    run = run_pytest(
        PytestRunRequest(
            role=RunRole.REPLAY,
            contract_id=guard.contract_id,
            contract_digest=guard.contract_digest,
            target=target_ref,
            target_digest=target_digest,
            test_path=workspace / guard.test_ref,
            known_case_ids=tuple(case.case_id for case in guard.cases),
            cwd=workspace,
            artifact_root=_workspace_path(Path(artifact_root), workspace),
            timeout_seconds=timeout_seconds,
        )
    )
    load_guard(path, cwd=workspace)
    if digest_file(workspace / target_ref.source_ref) != target_digest:
        raise ArtifactIntegrityError("Guard replay target changed during execution")
    return run


def _minimal_cases(contract: dict, evidence: Evidence) -> tuple[GuardCase, ...]:
    case_map = {case["case_id"]: case for case in contract["cases"]}
    if len(case_map) != len(contract["cases"]):
        raise ArtifactIntegrityError("Source contract contains duplicate case IDs")
    if not set(evidence.failing_case_ids).issubset(case_map):
        raise ArtifactIntegrityError("Evidence references an unknown contract case")
    return tuple(
        RaisesGuardCase.model_validate(case_map[case_id])
        if "raises" in case_map[case_id]
        else ValueGuardCase.model_validate(case_map[case_id])
        for case_id in evidence.failing_case_ids
    )


def _render_test(payload: dict, generator_version: str = "guard-test.v2") -> bytes:
    literal = repr(canonical_json_bytes(payload).decode("utf-8"))
    template = _TEST_TEMPLATE if generator_version == "guard-test.v1" else _TEST_TEMPLATE_V2
    return template.replace("__PAYLOAD__", literal).encode("utf-8")


def _workspace_path(path: Path, workspace: Path) -> Path:
    resolved = (path if path.is_absolute() else workspace / path).resolve()
    if not resolved.is_relative_to(workspace):
        raise ValueError("Guard path must resolve below cwd")
    return resolved
